# Send 4 commands like in Windows
ping -c4 ya.ru
# Unlimited sending commands ([ Ctrl ] + [ C ] to stop)
ping ya.ru
# Ping over IPv4
ping -4 ya.ru
# Ping over IPv6
ping -6 ya.ru

# Show ip address
ip addr show

# Network interfaces
ifconfig

# Trace route (requires install package: sudo apt install inetutils-traceroute)
traceroute ya.ru























